"""Read19 credential input and log redaction; engine transport stays in KaTrain."""

import re
import threading


def make_engine(katrain, config):
    from katrain.core.remote_engine import RemoteKataGoEngine, make_engine as upstream
    if config.get("backend") != "remote" or not config.get("remote_url", "").startswith("wss://read19.com/"):
        return upstream(katrain, config)

    class Read19Engine(RemoteKataGoEngine):
        def send_query(self, query, callback, error_callback, next_move=None, node=None):
            generation = self.query_generation

            def submit(attempt):
                if self._closing or generation != self.query_generation:
                    return
                payload = dict(query)
                if attempt:
                    payload.pop("id", None)

                def rejected(result):
                    if result.get("errorCode") == "CONCURRENCY_LIMIT_EXCEEDED" and attempt < 5:
                        self.katrain.log("Read19 busy; retrying analysis after a short wait")
                        timer = threading.Timer(2 ** (attempt + 1), submit, args=(attempt + 1,))
                        timer.daemon = True
                        timer.start()
                    elif error_callback:
                        error_callback(result)
                    else:
                        self.katrain.log("Read19 analysis failed: " + str(result.get("errorCode", "provider error")), 0)

                super(Read19Engine, self).send_query(payload, callback, rejected, next_move, node)

            submit(0)

    return Read19Engine(katrain, config)


def validate_read19_url(value):
    value = value.strip()
    if not re.fullmatch(r"wss://read19\.com/v1/katago/[A-Za-z0-9_-]+", value):
        raise ValueError("Use the complete secure KaTrain connection URL generated by your Read19 account")
    return value


def redact(message, config=None):
    text = str(message)
    url = (config or {}).get("engine", {}).get("remote_url", "")
    if url:
        text = text.replace(url, "[remote engine URL]")
        token = url.rstrip("/").rsplit("/", 1)[-1]
        if token:
            text = text.replace(token, "[credential]")
    return re.sub(r"wss?://[^\s\"'<>]+", "[remote engine URL]", text)
